import { access, writeFile } from 'node:fs/promises'
import { fileURLToPath, URL } from 'node:url'

const feedUrl = process.env.SUBSTACK_FEED_URL ?? 'https://boredletsgo.substack.com/feed'
const output = fileURLToPath(
  new URL('../src/data/substack.generated.ts', import.meta.url),
)

function decode(value = '') {
  return value
    .replace(/^<!\[CDATA\[|\]\]>$/g, '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/&#x([\da-f]+);/gi, (_, code) =>
      String.fromCodePoint(Number.parseInt(code, 16)),
    )
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replace(/\s+/g, ' ')
    .trim()
}

function field(item, name) {
  return decode(
    new RegExp(`<${name}(?:\\s[^>]*)?>([\\s\\S]*?)<\\/${name}>`, 'i').exec(item)?.[1],
  )
}

function parseFeed(xml) {
  return [...xml.matchAll(/<item>([\s\S]*?)<\/item>/gi)]
    .slice(0, 3)
    .map((match) => {
      const item = match[1]
      const published = field(item, 'pubDate')

      return {
        title: field(item, 'title'),
        description: field(item, 'description'),
        date: published
          ? new Date(published).toISOString().slice(0, 10)
          : new Date().toISOString().slice(0, 10),
        href: field(item, 'link'),
        category: field(item, 'category') || 'BoredLetsGo',
      }
    })
    .filter((post) => post.title && post.href)
}

try {
  const response = await fetch(feedUrl, {
    headers: { 'User-Agent': 'Mahima-Sahu-Portfolio/1.0' },
    signal: AbortSignal.timeout(10_000),
  })
  if (!response.ok) throw new Error(`HTTP ${response.status}`)

  const posts = parseFeed(await response.text())
  if (posts.length === 0) throw new Error('Feed contained no posts')

  await writeFile(
    output,
    `// Generated by scripts/sync-substack.mjs. Do not edit manually.\n` +
      `export const generatedSubstackPosts = ${JSON.stringify(posts, null, 2)} as const\n`,
  )
  console.log(`substack: synced ${posts.length} post(s)`)
} catch (error) {
  try {
    await access(output)
    console.warn(`substack: using cached posts (${error.message})`)
  } catch {
    throw new Error(`Substack sync failed and no cache exists: ${error.message}`)
  }
}
